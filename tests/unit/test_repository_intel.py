# 17. Context ranking tests
def test_context_ranking():
    sym = Symbol(
        id="sym::src/core.py::function::root::run",
        file="src/core.py",
        name="run",
        kind="function",
        start_line=5,
        end_line=15,
    )
    ref = SymbolReference(
        file="tests/test_core.py",
        symbol_name="run",
        line=10,
        resolved_symbol_id=sym.id,
    )
    index = RepositoryIndex(
        files={
            "src/core.py": RepositoryFile(path="src/core.py", bytes=200, line_count=20),
            "tests/test_core.py": RepositoryFile(path="tests/test_core.py", bytes=150, line_count=25, is_test=True),
        },
        symbols=[sym],
        references=[ref],
    )
    candidates = retrieve_context(index, changed_files=["src/core.py"], changed_symbols=[sym])
    assert len(candidates) >= 2
    assert candidates[0].score > candidates[1].score
    assert candidates[0].signals == ["changed_symbol"]
    assert candidates[1].signals == ["test_reference"]


