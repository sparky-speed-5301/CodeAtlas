# 11. Changed-symbol mapping
def test_changed_symbol_mapping():
    sym1 = Symbol(
        id="sym::src/auth.py::function::root::login",
        file="src/auth.py",
        name="login",
        kind="function",
        start_line=10,
        end_line=25,
    )
    sym2 = Symbol(
        id="sym::src/auth.py::function::root::logout",
        file="src/auth.py",
        name="logout",
        kind="function",
        start_line=30,
        end_line=45,
    )
    index = RepositoryIndex(
        files={"src/auth.py": RepositoryFile(path="src/auth.py", bytes=100, line_count=50)},
        symbols=[sym1, sym2],
    )
    diff = Diff(
        "base",
        "head",
        files=(
            FileChange(
                path="src/auth.py",
                status=ChangeStatus.MODIFIED,
                new_ranges=(LineRange(start=15, count=3),),
            ),
        ),
    )

    changed = identify_changed_symbols(index, diff)
    assert len(changed) == 1
    assert changed[0].name == "login"


